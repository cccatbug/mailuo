function initialLocale(): "zh-CN" | "en" {
  try {
    const stored = JSON.parse(
      localStorage.getItem("mailuo-settings") ?? "{}"
    ) as { locale?: string };
    return stored.locale === "en" ? "en" : "zh-CN";
  } catch {
    return "zh-CN";
  }
}

void i18n.use(initReactI18next).init({
  resources,
  lng: initialLocale(),
  fallbackLng: "zh-CN",
  interpolation: { escapeValue: false },
});

